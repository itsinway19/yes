-- Configuration identities reference the existing Provider enum keys, never provider instances.
CREATE TABLE business_types (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 key varchar(64) NOT NULL UNIQUE CHECK (key ~ '^[a-z][a-z0-9_]{0,63}$'),
 name_ar varchar(120) NOT NULL CHECK (length(trim(name_ar)) BETWEEN 2 AND 120),
 name_en varchar(120) NOT NULL CHECK (length(trim(name_en)) BETWEEN 2 AND 120),
 active boolean NOT NULL DEFAULT true,
 version bigint NOT NULL DEFAULT 1 CHECK (version > 0)
);
ALTER TABLE workspaces ADD COLUMN business_type_id bigint REFERENCES business_types(id) ON DELETE RESTRICT;
ALTER TABLE workspaces ADD COLUMN business_context_version bigint NOT NULL DEFAULT 0 CHECK (business_context_version >= 0);
CREATE INDEX workspaces_business_type_index ON workspaces(business_type_id);

CREATE TABLE business_source_guidance (
 business_type_id bigint NOT NULL REFERENCES business_types(id) ON DELETE RESTRICT,
 provider varchar(20) NOT NULL CHECK (provider IN ('meta','google','snapchat','tiktok','x')),
 priority integer NOT NULL CHECK (priority BETWEEN 0 AND 1000),
 rationale_ar varchar(600) NOT NULL CHECK (length(trim(rationale_ar)) > 0),
 rationale_en varchar(600) NOT NULL CHECK (length(trim(rationale_en)) > 0),
 active boolean NOT NULL DEFAULT true,
 PRIMARY KEY (business_type_id,provider)
);
CREATE TABLE business_promotion_priors (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 business_type_id bigint NOT NULL REFERENCES business_types(id) ON DELETE RESTRICT,
 provider varchar(20) NOT NULL,
 product varchar(64) NOT NULL,
 CONSTRAINT prior_product_provider CHECK (provider='google' AND product='google.search'),
 basis varchar(40) NOT NULL CHECK (basis IN ('ADMIN_APPROVED_HYPOTHESIS','EVIDENCE_SUPPORTED_PRIOR')),
 documented_basis text NOT NULL CHECK (length(trim(documented_basis)) BETWEEN 10 AND 4000),
 applicability text NOT NULL CHECK (length(trim(applicability)) BETWEEN 10 AND 2000),
 limits text NOT NULL CHECK (length(trim(limits)) BETWEEN 10 AND 2000),
 rationale_ar varchar(600) NOT NULL CHECK (length(trim(rationale_ar)) BETWEEN 10 AND 600),
 rationale_en varchar(600) NOT NULL CHECK (length(trim(rationale_en)) BETWEEN 10 AND 600),
 internal_rationale text NOT NULL CHECK (length(trim(internal_rationale)) BETWEEN 10 AND 4000),
 approved boolean NOT NULL DEFAULT false,
 active boolean NOT NULL DEFAULT false,
 approved_by bigint REFERENCES users(id) ON DELETE RESTRICT,
 approved_at timestamptz,
 version bigint NOT NULL DEFAULT 1 CHECK (version > 0),
 UNIQUE (business_type_id,provider,product),
 CHECK ((approved AND approved_by IS NOT NULL AND approved_at IS NOT NULL)
     OR (NOT approved AND approved_by IS NULL AND approved_at IS NULL))
);
CREATE TABLE business_context_events (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 workspace_id bigint NOT NULL REFERENCES workspaces(id) ON DELETE RESTRICT,
 actor_user_id bigint NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
 prior_type_id bigint REFERENCES business_types(id) ON DELETE RESTRICT,
 new_type_id bigint NOT NULL REFERENCES business_types(id) ON DELETE RESTRICT,
 prior_name varchar(255) NOT NULL,
 new_name varchar(255) NOT NULL,
 version bigint NOT NULL,
 occurred_at timestamptz NOT NULL DEFAULT clock_timestamp(),
 UNIQUE (workspace_id,version)
);

