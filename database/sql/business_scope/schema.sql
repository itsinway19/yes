 issuer_kind text NOT NULL CHECK(issuer_kind IN ('self_declared_draft','existing_grant','qualified_policy')),
 issuer_grant_id bigint REFERENCES security_action_grants(id) ON DELETE RESTRICT,
 subject_user_id bigint NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
 target_kind text NOT NULL, target_ref uuid NOT NULL,
 allowed_actions text[] NOT NULL, evidence_ref text NOT NULL, evidence_digest bytea NOT NULL CHECK(octet_length(evidence_digest)=32),
 status text NOT NULL CHECK(status IN ('active','revoked')), revision bigint NOT NULL CHECK(revision>0),
 valid_from timestamptz NOT NULL, valid_until timestamptz, provenance text NOT NULL,
 CHECK(valid_until IS NULL OR valid_until>valid_from)
);
CREATE TABLE business_workspace_links (
