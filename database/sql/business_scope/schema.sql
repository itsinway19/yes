CREATE TABLE businesses (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 public_id uuid NOT NULL UNIQUE CHECK(uuid_extract_version(public_id)=7),
 lifecycle text NOT NULL CHECK(lifecycle IN ('declared_draft','active','suspended','archived')),
 lifecycle_revision bigint NOT NULL DEFAULT 0 CHECK(lifecycle_revision>=0),
 origin_kind text NOT NULL CHECK(origin_kind IN ('self_declared_draft','qualified_import')),
 created_by bigint NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
 created_at timestamptz NOT NULL
);
CREATE TABLE business_context_heads (
 business_id bigint PRIMARY KEY REFERENCES businesses(id) ON DELETE RESTRICT,
 display_name text NOT NULL CHECK(length(btrim(display_name)) BETWEEN 2 AND 120),
 business_type_id bigint REFERENCES business_types(id) ON DELETE RESTRICT,
 context_version bigint NOT NULL DEFAULT 0 CHECK(context_version>=0)
);
CREATE TABLE business_current_intents (
 business_id bigint PRIMARY KEY REFERENCES businesses(id) ON DELETE RESTRICT,
 intent_revision bigint NOT NULL DEFAULT 0 CHECK(intent_revision>=0),
 value jsonb CHECK(value IS NULL OR value=public.builderad_current_intent_normalize(value))
);
CREATE TABLE business_authority_fences (
 business_id bigint PRIMARY KEY REFERENCES businesses(id) ON DELETE RESTRICT,
 auth_epoch bigint NOT NULL DEFAULT 0 CHECK(auth_epoch>=0)
);
CREATE TABLE migration_cohort_control (
 cohort_id uuid PRIMARY KEY CHECK(uuid_extract_version(cohort_id)=7),
 mode text NOT NULL CHECK(mode IN ('LEGACY_ACTIVE','DRAINING','V2_ACTIVE','RECOVERY_HOLD')),
 epoch bigint NOT NULL DEFAULT 0 CHECK(epoch>=0),
 guard_schema_version bigint NOT NULL DEFAULT 1 CHECK(guard_schema_version>=0),
 manifest_version bigint NOT NULL DEFAULT 0 CHECK(manifest_version>=0),
 checkpoint_digest bytea
);
CREATE TABLE migration_cohort_members (
 member_id uuid PRIMARY KEY CHECK(uuid_extract_version(member_id)=7),
 cohort_id uuid NOT NULL REFERENCES migration_cohort_control(cohort_id) ON DELETE RESTRICT,
 kind text NOT NULL CHECK(kind IN ('legacy_workspace','business')),
 workspace_id bigint REFERENCES workspaces(id) ON DELETE RESTRICT,
 business_id bigint REFERENCES businesses(id) ON DELETE RESTRICT,
 CHECK((kind='legacy_workspace' AND workspace_id IS NOT NULL AND business_id IS NULL)
    OR(kind='business' AND business_id IS NOT NULL AND workspace_id IS NULL))
);
CREATE UNIQUE INDEX cohort_workspace_unique ON migration_cohort_members(workspace_id) WHERE kind='legacy_workspace';
CREATE UNIQUE INDEX cohort_business_unique ON migration_cohort_members(business_id) WHERE kind='business';
CREATE TABLE authority_qualification_receipts (
 qualification_id uuid PRIMARY KEY CHECK(uuid_extract_version(qualification_id)=7),
