ALTER TABLE security_action_grants
 ADD COLUMN business_id bigint REFERENCES businesses(id) ON DELETE RESTRICT,
 ADD COLUMN boundary_id uuid, ADD COLUMN data_use_scope_id uuid,
 ADD COLUMN qualification_id uuid REFERENCES authority_qualification_receipts(qualification_id) ON DELETE RESTRICT,
 ADD COLUMN parent_grant_id bigint REFERENCES security_action_grants(id) ON DELETE RESTRICT,
 ADD COLUMN delegable boolean NOT NULL DEFAULT false,
 ADD COLUMN delegation_realm_kind text CHECK(delegation_realm_kind IN ('direct','agency')),
 ADD COLUMN delegation_workspace_id bigint REFERENCES workspaces(id) ON DELETE RESTRICT;
DO $body$
DECLARE prior text;
BEGIN
 SELECT pg_get_constraintdef(oid) INTO prior FROM pg_constraint WHERE conrelid='public.security_action_grants'::regclass AND conname='security_action_grants_scope_check';
 prior:=substring(prior FROM 8 FOR length(prior)-8);
 ALTER TABLE public.security_action_grants DROP CONSTRAINT security_action_grants_scope_check;
 EXECUTE 'ALTER TABLE public.security_action_grants ADD CONSTRAINT security_action_grants_scope_check CHECK (('||prior||
 ' AND business_id IS NULL AND boundary_id IS NULL AND data_use_scope_id IS NULL) OR
 (scope_kind IN (''business'',''client_data'',''data_use'') AND
 workspace_id IS NULL AND commercial_target_id IS NULL AND commercial_version_id IS NULL AND
 source_target_id IS NULL AND source_resource IS NULL AND source_operation IS NULL AND source_purpose IS NULL AND
 ((scope_kind=''business'' AND business_id IS NOT NULL AND boundary_id IS NULL AND data_use_scope_id IS NULL) OR
 (scope_kind=''client_data'' AND boundary_id IS NOT NULL AND business_id IS NULL AND data_use_scope_id IS NULL) OR
 (scope_kind=''data_use'' AND data_use_scope_id IS NOT NULL AND business_id IS NULL AND boundary_id IS NULL)) AND
 ((delegation_realm_kind=''direct'' AND delegation_workspace_id IS NULL) OR
 (delegation_realm_kind=''agency'' AND delegation_workspace_id IS NOT NULL))))';
 SELECT pg_get_constraintdef(oid) INTO prior FROM pg_constraint WHERE conrelid='public.security_action_grants'::regclass AND conname='security_action_grants_source_check';
 prior:=substring(prior FROM 8 FOR length(prior)-8);
 ALTER TABLE public.security_action_grants DROP CONSTRAINT security_action_grants_source_check;
 EXECUTE 'ALTER TABLE public.security_action_grants ADD CONSTRAINT security_action_grants_source_check CHECK
 ((scope_kind NOT IN (''business'',''client_data'',''data_use'') AND '||prior||') OR
 (scope_kind IN (''business'',''client_data'',''data_use'') AND
 ((source=''business_draft_creation'' AND granted_by IS NULL AND qualification_id IS NOT NULL AND parent_grant_id IS NULL AND NOT delegable) OR
 (source=''qualified_policy'' AND granted_by IS NULL AND qualification_id IS NOT NULL AND parent_grant_id IS NULL) OR
 (source=''qualified_delegation'' AND granted_by IS NOT NULL AND granted_by<>subject_user_id AND parent_grant_id IS NOT NULL))))';
END $body$;
