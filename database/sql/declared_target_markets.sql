-- Neutral identities and display metadata; no Commercial/provider eligibility.
CREATE TABLE country_references (
 code varchar(2) PRIMARY KEY CHECK (code ~ '^[A-Z]{2}$'),
 name_ar text NOT NULL CHECK (length(trim(name_ar)) > 0),
 name_en text NOT NULL CHECK (length(trim(name_en)) > 0)
);
CREATE TABLE business_target_markets (
 workspace_id bigint NOT NULL REFERENCES workspaces(id) ON DELETE RESTRICT,
 country_code varchar(2) NOT NULL REFERENCES country_references(code) ON DELETE RESTRICT,
 PRIMARY KEY (workspace_id,country_code)
);
CREATE TABLE business_target_market_events (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 workspace_id bigint NOT NULL REFERENCES workspaces(id) ON DELETE RESTRICT,
 actor_user_id bigint NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
 version bigint NOT NULL CHECK (version > 0),
 before_codes text[] NOT NULL CHECK (array_position(before_codes,NULL) IS NULL),
 after_codes text[] NOT NULL CHECK (array_position(after_codes,NULL) IS NULL),
 occurred_at timestamptz NOT NULL DEFAULT clock_timestamp(),
 UNIQUE (workspace_id,version),
 CHECK (before_codes <> after_codes)
);
ALTER TABLE business_target_markets ENABLE ROW LEVEL SECURITY;
ALTER TABLE business_target_markets FORCE ROW LEVEL SECURITY;
ALTER TABLE business_target_market_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE business_target_market_events FORCE ROW LEVEL SECURITY;
CREATE POLICY target_markets_owner ON business_target_markets TO builderad_owner USING (true) WITH CHECK (true);
CREATE POLICY target_market_events_owner ON business_target_market_events TO builderad_owner USING (true) WITH CHECK (true);
CREATE POLICY target_markets_read ON business_target_markets FOR SELECT TO builderad_app USING (
 workspace_id IN (SELECT c.workspace_id FROM builderad_signed_context() c WHERE c.phase='workspace')
);
CREATE POLICY target_market_events_read ON business_target_market_events FOR SELECT TO builderad_app USING (
 workspace_id IN (SELECT c.workspace_id FROM builderad_signed_context() c WHERE c.phase='workspace')
);
REVOKE ALL ON country_references,business_target_markets,business_target_market_events FROM PUBLIC,builderad_app,builderad_authority;
GRANT SELECT ON country_references,business_target_markets,business_target_market_events TO builderad_app;
CREATE TRIGGER target_market_event_immutable BEFORE UPDATE OR DELETE ON business_target_market_events
 FOR EACH ROW EXECUTE FUNCTION builderad_sa01_immutable();

CREATE FUNCTION builderad_business_target_markets_write(p_workspace bigint,p_session text,p_codes text[],p_version bigint)
RETURNS bigint LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path=public,pg_temp AS $$
DECLARE actor bigint; current_version bigint; prior_codes text[]; next_codes text[];
BEGIN
 -- Exactly the same prepared entry/serialization point as name/type mutation.
 PERFORM builderad_business_context_require_prepared(p_workspace);
 actor:=builderad_source_actor(p_workspace,p_session,false,false);
 SELECT business_context_version INTO current_version FROM workspaces WHERE id=p_workspace FOR UPDATE;
 PERFORM 1 FROM security_action_grants WHERE subject_user_id=actor AND workspace_id=p_workspace
  AND action='business.context.manage' AND scope_kind='workspace' FOR SHARE;
 actor:=builderad_source_actor(p_workspace,p_session,false,false);
 IF NOT EXISTS (SELECT 1 FROM security_action_grants g JOIN principal_lifecycles l ON l.user_id=g.subject_user_id
  WHERE g.subject_user_id=actor AND g.subject_generation=l.generation AND g.workspace_id=p_workspace
  AND g.action='business.context.manage' AND g.scope_kind='workspace' AND g.status='active' AND g.revoked_at IS NULL
  AND (g.expires_at IS NULL OR g.expires_at>clock_timestamp())) THEN
  RAISE EXCEPTION 'Explicit business context mutation grant required' USING ERRCODE='42501';
 END IF;
 IF p_codes IS NULL OR coalesce(array_ndims(p_codes),1)<>1 OR p_version IS NULL OR p_version<0 THEN
  RAISE EXCEPTION 'Canonical country list and nonnegative revision required' USING ERRCODE='22023';
 END IF;
 IF array_position(p_codes,NULL) IS NOT NULL OR cardinality(p_codes)>(SELECT count(*) FROM country_references)
  OR EXISTS (SELECT 1 FROM unnest(p_codes) AS submitted(code) WHERE submitted.code !~ '^[A-Z]{2}$'
   OR NOT EXISTS (SELECT 1 FROM country_references r WHERE r.code=submitted.code)) THEN
  RAISE EXCEPTION 'Canonical reference country codes required' USING ERRCODE='22023';
 END IF;
 SELECT coalesce(array_agg(DISTINCT code COLLATE "C" ORDER BY code COLLATE "C"),ARRAY[]::text[]) INTO next_codes FROM unnest(p_codes) code;
 SELECT coalesce(array_agg(country_code::text ORDER BY country_code COLLATE "C"),ARRAY[]::text[]) INTO prior_codes
  FROM business_target_markets WHERE workspace_id=p_workspace;
 IF prior_codes=next_codes THEN RETURN current_version; END IF;
 IF current_version<>p_version THEN
  RAISE EXCEPTION 'Business context changed; reload before retry' USING ERRCODE='40001';
 END IF;
 DELETE FROM business_target_markets WHERE workspace_id=p_workspace;
 INSERT INTO business_target_markets(workspace_id,country_code) SELECT p_workspace,code FROM unnest(next_codes) code;
 UPDATE workspaces SET business_context_version=current_version+1,updated_at=clock_timestamp() WHERE id=p_workspace;
 INSERT INTO business_target_market_events(workspace_id,actor_user_id,version,before_codes,after_codes)
  VALUES(p_workspace,actor,current_version+1,prior_codes,next_codes);
 -- Any FK/audit/row wait must not freeze earlier time-sensitive authority.
 actor:=builderad_source_actor(p_workspace,p_session,false,false);
 IF NOT EXISTS (SELECT 1 FROM security_action_grants g JOIN principal_lifecycles l ON l.user_id=g.subject_user_id
  WHERE g.subject_user_id=actor AND g.subject_generation=l.generation AND g.workspace_id=p_workspace
  AND g.action='business.context.manage' AND g.scope_kind='workspace' AND g.status='active' AND g.revoked_at IS NULL
  AND (g.expires_at IS NULL OR g.expires_at>clock_timestamp())) THEN
  RAISE EXCEPTION 'Business context authority expired before effect' USING ERRCODE='42501';
 END IF;
 RETURN current_version+1;
END $$;
REVOKE ALL ON FUNCTION builderad_business_target_markets_write(bigint,text,text[],bigint) FROM PUBLIC,builderad_authority;
GRANT EXECUTE ON FUNCTION builderad_business_target_markets_write(bigint,text,text[],bigint) TO builderad_app;
