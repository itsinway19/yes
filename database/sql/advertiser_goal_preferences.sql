-- A finite set of advertiser preferences. No canonical Intent/Purpose or provider execution.
CREATE FUNCTION builderad_advertiser_goals_normalize(v jsonb) RETURNS jsonb
LANGUAGE plpgsql IMMUTABLE SET search_path=public,pg_temp AS $$
DECLARE catalog jsonb := '{"sales":["actual_sales","purchasing_customers","sales_value","existing_customer_purchases"],"customers":["serious_inquiries","closer_to_purchase","fewer_unsuitable_inquiries","inquiry_sales_conversion"],"growth":["new_customer_groups","new_markets","new_needs","new_offerings"],"efficiency":["better_results","less_unproductive_spend","profitable_ad_sales","worthwhile_allocation"]}';
 keys text[]; goal jsonb; result jsonb; chosen jsonb; normalized_results jsonb := '{}'; allowed jsonb;
BEGIN
 IF v IS NULL OR octet_length(v::text)>8192 OR jsonb_typeof(v) IS DISTINCT FROM 'object' THEN
  RAISE EXCEPTION 'Exact bounded preferences required' USING ERRCODE='22023';
 END IF;
 SELECT array_agg(k ORDER BY k COLLATE "C") INTO keys FROM jsonb_object_keys(v) k;
 IF keys IS DISTINCT FROM ARRAY['goals','priority','results']::text[]
  OR jsonb_typeof(v->'goals') IS DISTINCT FROM 'array'
  OR jsonb_typeof(v->'results') IS DISTINCT FROM 'object'
  OR jsonb_typeof(v->'priority') IS DISTINCT FROM 'string' THEN
  RAISE EXCEPTION 'Complete goals, priority and results required' USING ERRCODE='22023';
 END IF;
 IF jsonb_array_length(v->'goals') NOT BETWEEN 1 AND 4 THEN
  RAISE EXCEPTION 'Select at least one available goal' USING ERRCODE='22023';
 END IF;
 chosen := '[]';
 FOR goal IN SELECT value FROM jsonb_array_elements(v->'goals') LOOP
  IF jsonb_typeof(goal) IS DISTINCT FROM 'string' OR NOT catalog ? (goal#>>'{}') OR chosen @> jsonb_build_array(goal) THEN
   RAISE EXCEPTION 'Unique available goal IDs required' USING ERRCODE='22023';
  END IF;
  chosen := chosen || jsonb_build_array(goal);
 END LOOP;
 IF NOT chosen @> jsonb_build_array(v->'priority') THEN
  RAISE EXCEPTION 'Priority must be one selected goal' USING ERRCODE='22023';
 END IF;
 IF EXISTS (SELECT 1 FROM jsonb_object_keys(v->'results') k WHERE NOT chosen @> jsonb_build_array(k)) THEN
  RAISE EXCEPTION 'Removed goals cannot have active results' USING ERRCODE='22023';
 END IF;
 FOR goal IN SELECT value FROM jsonb_array_elements(chosen) LOOP
  allowed := catalog->(goal#>>'{}');
  IF v->'results' ? (goal#>>'{}') AND jsonb_typeof(v->'results'->(goal#>>'{}')) IS DISTINCT FROM 'array' THEN
   RAISE EXCEPTION 'Result ID lists required' USING ERRCODE='22023';
  END IF;
  allowed := '[]';
  FOR result IN SELECT value FROM jsonb_array_elements(coalesce(v->'results'->(goal#>>'{}'),'[]'::jsonb)) LOOP
   IF jsonb_typeof(result) IS DISTINCT FROM 'string' OR NOT (catalog->(goal#>>'{}')) @> jsonb_build_array(result)
    OR allowed @> jsonb_build_array(result) THEN
    RAISE EXCEPTION 'Unique results belonging to the selected goal required' USING ERRCODE='22023';
   END IF;
   allowed := allowed || jsonb_build_array(result);
  END LOOP;
  SELECT coalesce(jsonb_agg(value ORDER BY (value#>>'{}') COLLATE "C"),'[]'::jsonb) INTO allowed FROM jsonb_array_elements(allowed);
  normalized_results := normalized_results || jsonb_build_object(goal#>>'{}',allowed);
 END LOOP;
 SELECT jsonb_agg(value ORDER BY (value#>>'{}') COLLATE "C") INTO chosen FROM jsonb_array_elements(chosen);
 RETURN jsonb_build_object('goals',chosen,'priority',v->'priority','results',normalized_results);
END $$;
REVOKE ALL ON FUNCTION builderad_advertiser_goals_normalize(jsonb) FROM PUBLIC,builderad_app,builderad_authority;

CREATE TABLE advertiser_goal_preferences (
 workspace_id bigint PRIMARY KEY REFERENCES workspaces(id) ON DELETE RESTRICT,
 value jsonb NOT NULL CHECK (value=builderad_advertiser_goals_normalize(value)),
 version bigint NOT NULL CHECK (version>0),
 actor_user_id bigint NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
 created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
 updated_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
CREATE TABLE advertiser_goal_preference_events (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 workspace_id bigint NOT NULL REFERENCES workspaces(id) ON DELETE RESTRICT,
 actor_user_id bigint NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
 version bigint NOT NULL CHECK (version>0),
 before_value jsonb NULL CHECK (before_value IS NULL OR before_value=builderad_advertiser_goals_normalize(before_value)),
 after_value jsonb NOT NULL CHECK (after_value=builderad_advertiser_goals_normalize(after_value)),
 occurred_at timestamptz NOT NULL DEFAULT clock_timestamp(),
 UNIQUE(workspace_id,version), CHECK(before_value IS DISTINCT FROM after_value)
);
ALTER TABLE advertiser_goal_preferences ENABLE ROW LEVEL SECURITY;
ALTER TABLE advertiser_goal_preferences FORCE ROW LEVEL SECURITY;
ALTER TABLE advertiser_goal_preference_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE advertiser_goal_preference_events FORCE ROW LEVEL SECURITY;
CREATE POLICY advertiser_goals_owner ON advertiser_goal_preferences TO builderad_owner USING(true) WITH CHECK(true);
CREATE POLICY advertiser_goal_events_owner ON advertiser_goal_preference_events TO builderad_owner USING(true) WITH CHECK(true);
CREATE POLICY advertiser_goals_read ON advertiser_goal_preferences FOR SELECT TO builderad_app USING
 (workspace_id IN (SELECT workspace_id FROM builderad_signed_context() WHERE phase='workspace'));
CREATE POLICY advertiser_goal_events_read ON advertiser_goal_preference_events FOR SELECT TO builderad_app USING
 (workspace_id IN (SELECT workspace_id FROM builderad_signed_context() WHERE phase='workspace'));
REVOKE ALL ON advertiser_goal_preferences,advertiser_goal_preference_events FROM PUBLIC,builderad_app,builderad_authority;
GRANT SELECT ON advertiser_goal_preferences,advertiser_goal_preference_events TO builderad_app;
REVOKE ALL ON SEQUENCE advertiser_goal_preference_events_id_seq FROM PUBLIC,builderad_app,builderad_authority;
CREATE FUNCTION builderad_advertiser_goal_event_immutable() RETURNS trigger
LANGUAGE plpgsql SET search_path=public,pg_temp AS $$
BEGIN RAISE EXCEPTION 'Preference audit history is immutable' USING ERRCODE='23514'; END $$;
REVOKE ALL ON FUNCTION builderad_advertiser_goal_event_immutable() FROM PUBLIC,builderad_app,builderad_authority;
CREATE TRIGGER advertiser_goal_event_immutable BEFORE UPDATE OR DELETE ON advertiser_goal_preference_events
 FOR EACH ROW EXECUTE FUNCTION builderad_advertiser_goal_event_immutable();

CREATE FUNCTION builderad_advertiser_goals_write(p_workspace bigint,p_session text,p_value jsonb,p_version bigint)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
DECLARE actor bigint; previous jsonb; current_version bigint; next_value jsonb;
BEGIN
 -- Signed Workspace identity and authority come from Foundation, never provider access.
 actor := builderad_current_workspace_actor(p_workspace,p_session,false,false);
 -- Independent rows/revision: no lock upgrade or write to workspaces/current_intent.
 PERFORM pg_advisory_xact_lock(hashtextextended('builderad.advertiser.goals.'||p_workspace::text,0));
 actor := builderad_current_workspace_actor(p_workspace,p_session,false,false);
 PERFORM 1 FROM security_action_grants WHERE subject_user_id=actor AND workspace_id=p_workspace
  AND action='business.context.manage' AND scope_kind='workspace' FOR SHARE;
 IF NOT EXISTS (SELECT 1 FROM security_action_grants g JOIN principal_lifecycles l ON l.user_id=g.subject_user_id
  WHERE g.subject_user_id=actor AND g.subject_generation=l.generation AND g.workspace_id=p_workspace
   AND g.action='business.context.manage' AND g.scope_kind='workspace' AND g.status='active' AND g.revoked_at IS NULL
   AND (g.expires_at IS NULL OR g.expires_at>clock_timestamp())) THEN
  RAISE EXCEPTION 'Explicit Workspace preference write authority required' USING ERRCODE='42501';
 END IF;
 next_value := builderad_advertiser_goals_normalize(p_value);
 IF p_version IS NULL OR p_version<0 THEN RAISE EXCEPTION 'Expected revision required' USING ERRCODE='22023'; END IF;
 SELECT value,version INTO previous,current_version FROM advertiser_goal_preferences WHERE workspace_id=p_workspace FOR UPDATE;
 current_version := coalesce(current_version,0);
 IF current_version<>p_version THEN RAISE EXCEPTION 'Saved preferences changed' USING ERRCODE='40001'; END IF;
 IF previous IS DISTINCT FROM next_value THEN
  INSERT INTO advertiser_goal_preferences(workspace_id,value,version,actor_user_id)
  VALUES(p_workspace,next_value,current_version+1,actor)
  ON CONFLICT(workspace_id) DO UPDATE SET value=EXCLUDED.value,version=EXCLUDED.version,actor_user_id=actor,updated_at=clock_timestamp();
  INSERT INTO advertiser_goal_preference_events(workspace_id,actor_user_id,version,before_value,after_value)
  VALUES(p_workspace,actor,current_version+1,previous,next_value);
  current_version := current_version+1;
 END IF;
 actor := builderad_current_workspace_actor(p_workspace,p_session,false,false);
 IF NOT EXISTS (SELECT 1 FROM security_action_grants g JOIN principal_lifecycles l ON l.user_id=g.subject_user_id
  WHERE g.subject_user_id=actor AND g.subject_generation=l.generation AND g.workspace_id=p_workspace
   AND g.action='business.context.manage' AND g.scope_kind='workspace' AND g.status='active' AND g.revoked_at IS NULL
   AND (g.expires_at IS NULL OR g.expires_at>clock_timestamp())) THEN
  RAISE EXCEPTION 'Preference authority expired before effect' USING ERRCODE='42501';
 END IF;
 RETURN jsonb_build_object('value',next_value,'version',current_version);
END $$;
REVOKE ALL ON FUNCTION builderad_advertiser_goals_write(bigint,text,jsonb,bigint) FROM PUBLIC,builderad_authority;
GRANT EXECUTE ON FUNCTION builderad_advertiser_goals_write(bigint,text,jsonb,bigint) TO builderad_app;
